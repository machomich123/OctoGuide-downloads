-- Runs the original regression harness, then exercises actual runtime/UI mode changes.
dofile('tests/test-runtime.lua')
local G=OctoGuide
local passed=0
local function check(name,fn) fn();passed=passed+1;print('PASS MODE '..name) end
G.RegisterGuide({id='mode-route',title='Two routes',faction='Horde',startLevel=1,endLevel=5,modes={normal=true,hardcore=true}}, {
 {id='common-start',action='travel',text='Shared start',zone=1,x=.1,y=.1},
 {id='normal-shortcut',branch='return-home',mode='normal',requiresDeath=true,action='death',text='Normal shortcut',zone=1,x=.2,y=.2},
 {id='hc-return',branch='return-home',mode='hardcore',action='travel',text='Walk home',zone=1,x=.3,y=.3},
 {id='common-end',action='travel',text='Shared destination',zone=1,x=.4,y=.4}
})
G.RegisterGuide({id='normal-only',title='Normal only',faction='Horde',startLevel=5,endLevel=6,modes={normal=true}},{{id='one',action='travel',text='Normal route'}})
G.RegisterGuide({id='mislabel-death',title='Incorrect death label',faction='Horde',startLevel=5,endLevel=6,modes={hardcore=true}},{{id='one',modes={hardcore=true},requiresDeath=true,action='travel',text='Requires death'}})
G.RegisterGuide({id='unflagged-death',title='Death action',faction='Horde',startLevel=5,endLevel=6},{{id='one',action='death',text='Death action'}})
check('first login defaults to hardcore; invalid setting is repaired',function()
 OctoGuideDB={mode='typo'};G.ready=false;G.Init();assert(G.Mode()=='hardcore' and G.db.mode=='hardcore')
end)
check('hardcore route excludes every death shortcut',function()
 assert(G.Select('mode-route'));assert(table.getn(G.state.steps)==3 and G.state.steps[2].id=='hc-return')
 assert(not G.Playable(G.guides['unflagged-death']) and not G.Playable(G.guides['mislabel-death']))
end)
check('mislabelled hardcore metadata cannot override death flag',function()
 assert(not G.ModeAllowed({modes={hardcore=true},requiresDeath=true},'hardcore'))
 assert(not G.ModeAllowed({mode='hardcore',action='death'},'hardcore'))
 assert(not G.Select('mislabel-death'))
end)
check('common progress survives and new mode gets correct current waypoint',function()
 G.Mark('manual');assert(G.Current().id=='hc-return');assert(G.frame.distance.value=='424 yd')
 G.Slash('normal');assert(G.Mode()=='normal' and G.Current().id=='normal-shortcut' and table.getn(G.state.steps)==3)
 assert(G.frame.distance.value=='283 yd' and G.db.progress['mode-route:common-start']=='manual')
end)
check('normal branch completion does not complete hardcore alternative',function()
 G.Mark('skipped');assert(G.Current().id=='common-end');G.Slash('hardcore');assert(G.Current().id=='hc-return')
 assert(G.db.progress['mode-route:normal-shortcut:mode:normal']=='skipped' and not G.db.progress['mode-route:hc-return:mode:hardcore'])
end)
check('repeated mode switching restores each branch state',function()
 G.Mark('manual');assert(G.Current().id=='common-end');G.SetMode('normal');assert(G.Current().id=='common-end')
 G.SetMode('hardcore');assert(G.Current().id=='common-end');G.Back();assert(G.Current().id=='hc-return')
 G.SetMode('normal');assert(G.Current().id=='common-end');G.SetMode('hardcore');assert(G.Current().id=='hc-return')
end)
check('old unscoped branch skips are not migrated to new alternatives',function()
 G.db.progress['mode-route:hc-return']='skipped';assert(G.Current().id=='hc-return')
 G.db.progress['mode-route:normal-shortcut:mode:normal']=nil;G.db.progress['mode-route:normal-shortcut']='skipped'
 G.SetMode('normal');assert(G.Current().id=='normal-shortcut')
end)
check('mode setting and branch progress persist through reload',function()
 G.Mark('manual');local saved=G.db;G.ready=false;G.Init();assert(G.db==saved and G.Mode()=='normal' and G.Current().id=='common-end')
end)
check('visible mode button works in minimal and full views',function()
 G.Slash('minimal');assert(G.frame.routeMode.value=='Normal');this=G.frame.routeMode;this.scripts.OnClick();assert(G.Mode()=='hardcore' and G.frame.routeMode.value=='Hardcore')
 G.Slash('full');this=G.frame.routeMode;this.scripts.OnClick();assert(G.Mode()=='normal' and G.frame.routeMode.value=='Normal' and G.frame.nextCard:IsShown())
end)
check('menu omits unavailable guides and updates when mode changes',function()
 G.SetMode('hardcore');G.RenderMenu();for _,row in ipairs(G.menu.rows) do assert(row.guideID~='normal-only' and row.guideID~='mislabel-death' and row.guideID~='unflagged-death') end
 G.SetMode('normal');G.RenderMenu();local found=false;for _,row in ipairs(G.menu.rows) do if row.guideID=='normal-only' then found=true end end;assert(found)
end)
check('switching mode from incompatible guide selects a playable fallback',function()
 assert(G.Select('normal-only'));G.SetMode('hardcore');assert(G.state.guide.id~='normal-only' and G.Playable(G.state.guide) and G.db.guide==G.state.guide.id)
end)
check('explicit next stage cannot select incompatible guide',function()
 G.Select('mode-route');G.state.guide.nextGuide='normal-only';assert(G.NextStage());assert(G.state.guide.id~='normal-only' and G.Playable(G.state.guide))
end)
check('invalid modes and hidden unknown actions fail registration',function()
 local ok=pcall(G.RegisterGuide,{id='badmode',faction='Horde'},{{id='a',action='travel',text='Bad',mode='safe'}});assert(not ok and not G.guides.badmode)
 ok=pcall(G.RegisterGuide,{id='badflag',faction='Horde'},{{id='a',action='travel',text='Bad',requiresDeath='yes'}});assert(not ok and not G.guides.badflag)
 ok=pcall(G.RegisterGuide,{id='badaction',faction='Horde'},{{id='a',action='unknown-shortcut',text='Bad'}});assert(not ok and not G.guides.badaction)
 ok=pcall(G.RegisterGuide,{id='badset',faction='Horde',modes={normal=true,pvp=true}},{{id='a',action='travel',text='Bad'}});assert(not ok and not G.guides.badset)
end)
check('invalid mode request does not change saved mode',function()
 local old=G.Mode();assert(not G.SetMode('invalid'));assert(G.Mode()==old)
end)
check('all registered allowed hardcore steps are death-free',function()
 G.SetMode('hardcore');for _,guide in pairs(G.guides) do if G.Playable(guide) then for _,s in ipairs(guide.steps) do if G.Allowed(s) then assert(not s.requiresDeath and s.action~='death') end end end end
end)
check('fractional level gate reads actual XP and handles missing API',function()
 local original=UnitLevel;UnitLevel=function() return 12 end
 assert(not G.Satisfied({action='level',level=12,xpFraction=.82}))
 UnitXP=function() return 81 end;UnitXPMax=function() return 100 end;assert(not G.Satisfied({action='level',level=12,xpFraction=.82}))
 UnitXP=function() return 82 end;assert(G.Satisfied({action='level',level=12,xpFraction=.82}))
 UnitLevel=function() return 13 end;UnitXP=nil;assert(G.Satisfied({action='level',level=12,xpFraction=.82}))
 UnitLevel=original;UnitXP=nil;UnitXPMax=nil
end)
check('fractional level gate fails closed for broken XP API',function()
 local original=UnitLevel;UnitLevel=function() return 12 end;UnitXP=function() error('no XP') end;UnitXPMax=function() return 100 end
 assert(not G.Satisfied({action='level',level=12,xpFraction=.5}))
 UnitXP=function() return 90 end;UnitXPMax=function() return 0 end;assert(not G.Satisfied({action='level',level=12,xpFraction=.5}))
 UnitLevel=original;UnitXP=nil;UnitXPMax=nil
end)
check('manual partial objective is explicit but known turnin clears old step',function()
 assert(not G.Satisfied({action='complete',questID=887755,manual=true}))
 G.db.completedQuests[887755]=true;assert(G.Satisfied({action='complete',questID=887755,manual=true}));G.db.completedQuests[887755]=nil
end)
check('invalid fractional gates and manual flags fail registration',function()
 local ok=pcall(G.RegisterGuide,{id='badxp',faction='Horde'},{{id='a',action='level',text='Bad',level=12,xpFraction=1}});assert(not ok and not G.guides.badxp)
 ok=pcall(G.RegisterGuide,{id='badmanual',faction='Horde'},{{id='a',action='complete',text='Bad',manual='yes'}});assert(not ok and not G.guides.badmanual)
end)
print('ALL '..passed..' MODE CHECKS PASSED (plus original 28 runtime checks)')
